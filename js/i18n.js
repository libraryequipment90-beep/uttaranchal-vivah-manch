function getLang() {
  return localStorage.getItem("uv-lang") || "hi";
}

function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || I18N.hi[key] || key;
}

function communityLabel(key) {
  return { brahmin: t("brahmin"), rajput: t("rajput"), other: t("other") }[key] || key;
}

function genderLabel(key) {
  return key === "groom" ? t("grooms") : t("brides");
}

function applyLang() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const val = t(el.getAttribute("data-i18n"));
    if (el.hasAttribute("data-i18n-html")) el.innerHTML = val;
    else el.textContent = val;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.getAttribute("data-i18n-placeholder"));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    document.title = t(el.getAttribute("data-i18n-title"));
  });
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  if (typeof window.onLangChange === "function") window.onLangChange();
}

function setLang(lang) {
  localStorage.setItem("uv-lang", lang);
  applyLang();
}
